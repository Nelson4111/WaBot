export function rollInterstellarItem(random = Math.random, tierMultipliers = {}) {
  const weightFor = item => item.weight * (Number(tierMultipliers[item.tier]) || 1)
  const totalWeight = INTERSTELLAR_ITEMS.reduce((sum, item) => sum + weightFor(item), 0)
  let roll = random() * totalWeight
  for (const item of INTERSTELLAR_ITEMS) {
    roll -= weightFor(item)
    if (roll < 0) return item
  }
  return INTERSTELLAR_ITEMS[0]
}
