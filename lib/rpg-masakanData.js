export function normalizeMasakanKey(input = '') {
  return String(input || '')
    .trim()
    .toLowerCase()
    .replace(/\s+/g, '_')
    .replace(/\-+/g, '_')
}

export function formatMasakanNama(input = '') {
  const raw = normalizeMasakanKey(input)
  return raw
    .split('_')
    .filter(Boolean)
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ')
}
